#!/usr/bin/env python3
"""Export catalog metadata, swatches and SMWL overlays for baked and layered rooms."""
import argparse
from pathlib import Path
import struct
import zlib

from PIL import Image, ImageChops
import prepare_room_background as room
from compose_room import composite, render_base
from wallpaper_catalog import CATALOG, catalog_table, load_catalog
from extend_ui_font import with_ui_glyphs
from generate_font16cn import collect_chars_from_text

ART = CATALOG.parent
HEADER = struct.Struct('<4sHHHHHH')
ENTRY = struct.Struct('<IIIII')  # Base fingerprint, offset, compressed bytes, CRC32, raw bytes.
MODES = ('day', 'night')


def fingerprint(data):
    value = 2166136261
    for byte in data:
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return value


def encode_patch(before, after, bounds):
    # Each patch shares a small wall bounding box. A set bit selects one RGB565
    # replacement. Other pixels, including opaque foreground, keep their source.
    original = room.rgb565_bytes(before.crop(bounds))
    result = room.rgb565_bytes(after.crop(bounds))
    count = len(result) // 2
    mask = bytearray((count + 7) // 8)
    colors = bytearray()
    for pixel in range(count):
        offset = 2 * pixel
        if original[offset:offset+2] != result[offset:offset+2]:
            mask[pixel // 8] |= 1 << (pixel % 8)
            colors.extend(result[offset:offset+2])
    return bytes(mask + colors)


def wallpaper_pack(overlay_path):
    overlay = Image.open(overlay_path).convert('RGBA')
    mask = Image.open(overlay_path.parent / 'walls-mask.png').convert('RGBA').getchannel('A')
    if overlay.size != mask.size or mask.getextrema() != (0, 255):
        raise ValueError(f'{overlay_path} and wall mask must share the native room canvas')
    overlay.putalpha(ImageChops.multiply(overlay.getchannel('A'), mask))
    bounds = overlay.getbbox()
    if bounds is None:
        raise ValueError(f'{overlay_path} leaves no visible walls inside the mask')
    x, y, right, bottom = bounds
    layout = room.layout_without_preview_sprites(room.read_layout(room.DEFAULT_LAYOUT))
    art = room.scale_room_layout_for_art(layout, room.ROOM_ART_SCALE)
    if room.room_size(art) != overlay.size:
        raise ValueError(f'{overlay_path} canvas does not match room art')
    directory = room.DEFAULT_LAYOUT.parent
    entries, streams, offsets = [], bytearray(), {}
    for layered in (False, True):
        for mode in MODES:
            path = room.background_path(room.DEFAULT_LAYOUT, layout, mode)
            if layered:
                before = render_base(art, path, mode, directory)
                after = Image.alpha_composite(before, overlay)
            else:
                before = room.compose_room_image(art, path, room.DEFAULT_FURNITURE_DIR, mode, directory)
                after = composite(art, path, room.DEFAULT_FURNITURE_DIR, mode, include_lighting=False,
                                  layout_dir=directory, wall_overlay=overlay)
            raw = encode_patch(before, after, bounds)
            compressed = room.raw_deflate(raw)
            if compressed not in offsets:
                offsets[compressed] = HEADER.size + 4 * ENTRY.size + len(streams)
                streams.extend(compressed)
            entries.append(ENTRY.pack(fingerprint(room.rgb565_bytes(before)),
                                      offsets[compressed], len(compressed), zlib.crc32(raw), len(raw)))
    return HEADER.pack(b'SMWL', 1, x, y, right-x, bottom-y, 0) + b''.join(entries) + streams


def array(name, ctype, values, fmt):
    rows = [', '.join(format(v, fmt) for v in values[i:i+16]) for i in range(0, len(values), 16)]
    return f'inline constexpr {ctype} {name}[] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def icon_arrays(symbol, path, size):
    image = Image.open(path).convert('RGBA')
    if image.size != (size, size):
        raise ValueError(f'Expected {size}x{size} pixels in {path}')
    colors, indices = {}, []
    for r, g, b, a in (image.get_flattened_data() if hasattr(image, 'get_flattened_data') else image.getdata()):
        if a not in (0, 255):
            raise ValueError(f'Expected binary transparency in {path}')
        color = room.rgb565(r, g, b)
        indices.append(colors.setdefault(color, len(colors)+1) if a else 0)
    if len(colors) > 255:
        raise ValueError(f'{path} exceeds indexed palette')
    return (array(symbol+'Palette', 'uint16_t', [0, *colors], '#06x') +
            array(symbol+'Pixels', 'uint8_t', indices, 'd'))


def icons(entries, directory):
    output = '// Generated by tools/generate_room_wallpaper.py. Index 0 is transparent.\n'
    rows = []
    for index, entry in enumerate(entries):
        symbol = f"Swatch{entry['id']}"
        output += (f"static_assert(static_cast<uint8_t>(Game::MarketWorkshop::WALLPAPERS[{index}].id)"
                   f" == {entry['id']}, \"Regenerate wallpaper swatches with the catalog\");\n")
        output += icon_arrays(symbol, directory / entry['swatch'], 32)
        rows.append(f'    {{{symbol}Pixels, {symbol}Palette}},\n')
    output += 'inline constexpr Swatch Swatches[] = {\n' + ''.join(rows) + '};\n'
    return output + icon_arrays('Workshop', directory / 'workshop-wallpaper.png', 48)


def generate(catalog=CATALOG, output_root=room.ROOT):
    entries = load_catalog(catalog)
    headers = output_root / 'src/assets'
    rooms = output_root / 'data/packs/dev/rooms'
    # Validate and encode all sources before publishing any new table or pack.
    outputs = {headers / 'WallpaperCatalog.inc': catalog_table(entries).encode('utf-8'),
               headers / 'WallpaperIcons.inc': icons(entries, catalog.parent).encode('utf-8')}
    for entry in entries:
        asset = entry['asset']
        if asset is not None:
            outputs[rooms / f'{asset}.smonwall'] = wallpaper_pack(catalog.parent / f'{asset}.png')
    fonts = rooms.parent / 'fonts'
    if fonts.is_dir():
        chars = collect_chars_from_text(''.join(entry['name'] for entry in entries))
        for name in ('zh16', 'zh32', 'round-zh16-a4', 'round-zh20-a4'):
            path = fonts / (name + '.smonfont')
            previous = path.read_bytes()
            updated = with_ui_glyphs(previous, chars)
            if previous != updated:
                outputs[path] = updated
    for path, data in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, default=CATALOG)
    parser.add_argument('--output-root', type=Path, default=room.ROOT)
    args = parser.parse_args()
    generate(args.catalog, args.output_root)
