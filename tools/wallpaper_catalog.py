"""Authored wallpaper metadata and resource selection (also used by firmware staging)."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'origin_asset/room/wallpapers/catalog.json'


def load_catalog(path=CATALOG):
    entries = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(entries, list):
        raise ValueError(f'{path}: expected a wallpaper list')
    ids, assets = set(), set()
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != {'id', 'name', 'price', 'asset', 'swatch'}:
            raise ValueError(f'{path}: expected id, name, price, asset and swatch')
        ident, name, price = entry['id'], entry['name'], entry['price']
        if type(ident) is not int or not 0 <= ident <= 255 or ident in ids:
            raise ValueError(f'{path}: invalid or duplicate wallpaper ID {ident!r}')
        ids.add(ident)
        if not isinstance(name, str) or not name.strip() or not name.isprintable():
            raise ValueError(f'{path}: invalid wallpaper name for ID {ident}')
        if len(name) > 4:
            raise ValueError(f'{path}: wallpaper name for ID {ident} exceeds 4 characters: {name!r}')
        if type(price) is not int or not 0 <= price <= 65535:
            raise ValueError(f'{path}: invalid wallpaper price for ID {ident}')
        asset = entry['asset']
        if ident == 0:
            if asset is not None or price != 0:
                raise ValueError(f'{path}: original room must be free with a null asset')
        else:
            # V2 SPIFFS permits 63 bytes including the /packs/dev/rooms/ prefix and .smonwall.
            if not isinstance(asset, str) or not re.fullmatch(r'[a-z0-9][a-z0-9_-]{0,36}', asset):
                raise ValueError(f'{path}: invalid wallpaper asset basename {asset!r}')
            if asset in assets:
                raise ValueError(f'{path}: duplicate wallpaper asset {asset!r}')
            assets.add(asset)
        swatch = entry['swatch']
        if not isinstance(swatch, str) or not re.fullmatch(r'[a-zA-Z0-9_-]+\.png', swatch):
            raise ValueError(f'{path}: invalid swatch filename {swatch!r}')
    if 0 not in ids:
        raise ValueError(f'{path}: missing original room (ID 0)')
    return entries


def catalog_table(entries):
    rows = ['// Generated by tools/generate_room_wallpaper.py.\n']
    for entry in entries:
        asset = json.dumps(entry['asset']) if entry['asset'] is not None else 'nullptr'
        name = json.dumps(entry['name'], ensure_ascii=False)
        rows.append(f"    {{static_cast<Wallpaper>({entry['id']}), {name}, {entry['price']}, {asset}}},  // {entry['swatch']}\n")
    return ''.join(rows)


def exported_wallpapers(data, catalog=CATALOG):
    entries = load_catalog(catalog)
    table = data.resolve().parent / 'src/assets/WallpaperCatalog.inc'
    if table.is_file() or data.resolve() == ROOT / 'data':
        if not table.is_file() or table.read_text(encoding='utf-8') != catalog_table(entries):
            raise ValueError(f'Stale {table}. Run tools/generate_room_wallpaper.py')
    paths = [data / 'packs/dev/rooms' / (entry['asset'] + '.smonwall')
             for entry in entries if entry['asset'] is not None]
    for path in paths:
        if not path.is_file():
            raise ValueError(f'Missing {path}. Run tools/generate_room_wallpaper.py')
    return paths


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='List declared room wallpaper packs for staging')
    parser.add_argument('--catalog', type=Path, default=CATALOG)
    parser.add_argument('--data', type=Path, default=ROOT / 'data')
    args = parser.parse_args()
    for path in exported_wallpapers(args.data, args.catalog):
        print(path)
