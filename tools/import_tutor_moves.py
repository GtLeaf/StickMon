#!/usr/bin/env python3
"""Generate the TM/tutor compatibility table used by the market move tutor.

Source: Pokemon Essentials Gen 6 PBS (`PBS/Gen 6 backup/pokemon.txt`), the
`TutorMoves` line of every roster species (TMs, HMs and move tutors of the
ORAS era, matching the existing ORAS level-up snapshot). Only moves already
present in the battle move table are kept; unsupported effects are filtered
again at runtime by `isMoveBattleSupported`.

Usage:
    python3 tools/import_tutor_moves.py [--essentials DIR] [--check]
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import sys
from import_pokeapi_learnsets import REMOVED_SYSTEM_DEPENDENT_MOVES

ROOT = Path(__file__).resolve().parents[1]
ROSTER = ROOT / 'tools/pokemon_data/species_roster.json'
SNAPSHOT = ROOT / 'tools/pokemon_data/oras_learnsets.json'
OUTPUT = ROOT / 'src/game/MoveTutorData.inc'
REPORT = ROOT / 'tools/pokemon_data/oras_tutor_moves.json'
PBS_RELATIVE = Path('PBS/Gen 6 backup/pokemon.txt')


def essentials_dir(value):
    if value:
        return Path(value)
    return Path(os.environ.get('ESSENTIALS_DIR', ROOT / 'external/pokemon-essentials'))


def parse_pbs(path):
    text = path.read_text(encoding='utf-8-sig')
    species = {}
    for number, block in enumerate(re.split(r'(?m)^\[', text)[1:], 1):
        name = block.split(']', 1)[0].strip()
        match = re.search(r'(?m)^TutorMoves\s*=\s*(.*)$', block)
        moves = [m.strip() for m in match.group(1).split(',')] if match else []
        species[number] = (name, [m for m in moves if m])
    return species


def build(essentials):
    pbs = essentials / PBS_RELATIVE
    if not pbs.is_file():
        raise SystemExit(f'Essentials Gen 6 PBS not found: {pbs} (set ESSENTIALS_DIR)')
    roster = json.loads(ROSTER.read_text())['speciesIds']
    snapshot = json.loads(SNAPSHOT.read_text())
    # The snapshot also contains PP/held-item moves deliberately removed from
    # OFFICIAL_MOVES. Apply the same filter as the level-up table generator.
    move_ids = {m['identifier'].replace('-', '').upper(): m['id'] for m in snapshot['moves']
                if m['identifier'] not in REMOVED_SYSTEM_DEPENDENT_MOVES}
    parsed = parse_pbs(pbs)
    learnsets, entries, report = [], [], {}
    for species_id in sorted(roster):
        name, tutor = parsed[species_id]
        ids = sorted({move_ids[m] for m in tutor if m in move_ids})
        if ids:
            learnsets.append((species_id, len(entries), len(ids)))
            entries.extend(ids)
        report[str(species_id)] = {'name': name, 'source': len(tutor), 'kept': ids}
    return pbs, learnsets, entries, report


def render(pbs, learnsets, entries):
    digest = hashlib.sha256(pbs.read_bytes()).hexdigest()
    lines = [
        '// Generated by tools/import_tutor_moves.py. Do not edit.',
        f'// Source: Pokemon Essentials {PBS_RELATIVE.as_posix()} TutorMoves, sha256 {digest}.',
        '// Only moves present in OFFICIAL_MOVES are kept.',
        '#if !STICKMON_EXTERNAL_CONTENT',
        'static const Game::MoveId TUTOR_MOVE_ENTRIES[] = {',
    ]
    for i in range(0, len(entries), 16):
        lines.append('    ' + ', '.join(str(v) for v in entries[i:i + 16]) + ',')
    lines += ['};', 'static const SpeciesTutorMoves TUTOR_MOVE_SETS[] = {']
    lines += [f'    {{{s}, {o}, {c}}},' for s, o, c in learnsets]
    lines += ['};', '#define TUTOR_MOVE_SET_COUNT (sizeof(TUTOR_MOVE_SETS) / sizeof(TUTOR_MOVE_SETS[0]))',
              '#define TUTOR_MOVE_ENTRY_COUNT (sizeof(TUTOR_MOVE_ENTRIES) / sizeof(TUTOR_MOVE_ENTRIES[0]))',
              '#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--essentials')
    parser.add_argument('--check', action='store_true', help='fail if the generated file is stale')
    args = parser.parse_args()
    pbs, learnsets, entries, report = build(essentials_dir(args.essentials))
    text = render(pbs, learnsets, entries)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.exit(f'{OUTPUT.relative_to(ROOT)} is stale; rerun tools/import_tutor_moves.py')
        print('tutor move table up to date')
        return
    OUTPUT.write_text(text)
    REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=1) + '\n')
    print(f'species={len(learnsets)} entries={len(entries)} -> {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
