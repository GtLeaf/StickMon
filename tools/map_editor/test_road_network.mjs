import assert from 'node:assert/strict';
import {History, copy, worldPoints, syncJunction} from './model.js';
import {recognizeRoads, currentRoadNetwork, routeFromRoads, storeRoadRoute, roadRouteCurrent} from './road-network.js';
const catalog = {assets:{grass:{}, road:{road:true,runtimeId:546}, wall:{depth:[0,1,0]}, canopy:{depth:[0,2,0],behind:[false,true,false]}}};
const blank = () => ({map:{layers:[Array(192).fill('grass'),Array(192).fill(null),Array(192).fill(null)],objects:[],paths:[]},prefabs:[]});
const put = (p,x,y,w,h,key='road') => {for(let b=y;b<y+h;b++)for(let a=x;a<x+w;a++)p.map.layers[0][b*16+a]=key;};
const p=blank(); put(p,4,0,2,12);
const before=copy(p), straight=recognizeRoads(p,catalog);
assert.deepEqual(p,before);
assert.deepEqual(straight.nodes,Array.from({length:11},(_,i)=>[5,i+1]).concat([[5,0],[5,12]]));
assert.equal(straight.edges.length,12); assert.equal(straight.components,1);assert.equal(straight.uncovered.length,0);
const ring=blank();put(ring,3,2,7,2);put(ring,3,7,7,2);put(ring,3,2,2,7);put(ring,8,2,2,7);
put(ring,0,4,5,2);
const network=recognizeRoads(ring,catalog);
assert.equal(network.components,1);assert.equal(network.edges.length-network.nodes.length+1,1);assert.equal(network.junctions,1);
const blocked=copy(p);blocked.map.layers[1][5*16+4]='wall';
assert.equal(recognizeRoads(blocked,catalog).components,2);
blocked.map.layers[1][5*16+4]='canopy';assert.equal(recognizeRoads(blocked,catalog).components,1);
blocked.prefabs=[{id:'crate',cells:[{x:0,y:0,layer:1,asset:'wall'}],footprint:[[0,0]]}];
blocked.map.objects=[{id:'crate-1',prefab:'crate',x:4,y:5}];assert.equal(recognizeRoads(blocked,catalog).components,2);
const narrow=blank();put(narrow,3,2,1,6);assert.throws(()=>recognizeRoads(narrow,catalog),/双格/);
assert.throws(()=>recognizeRoads(blank(),catalog),/没有道路/);
// Touching outer borders must not merge two separately capped strips.
const strips=blank(), tiles=[537,538,539,545,547,553,554,555];
for(const id of tiles)catalog.assets[String(id)]={road:true,runtimeId:id};
for(let y=2;y<=7;y++) for(let x=3;x<=6;x++) strips.map.layers[0][y*16+x]=String(y===2?(x%2?537:539):y===7?(x%2?553:555):(x%2?545:547));
assert.equal(recognizeRoads(strips,catalog).components,2);
const history=new History(p);history.change(v=>v.map.roadNetwork=straight);
assert.ok(currentRoadNetwork(history.project));history.undo();assert.equal(currentRoadNetwork(history.project),null);history.redo();
assert.deepEqual(currentRoadNetwork(JSON.parse(JSON.stringify(history.project))),straight);
history.change(v=>v.map.layers[0][4]='grass');assert.equal(currentRoadNetwork(history.project),null);history.undo();assert.ok(currentRoadNetwork(history.project));
console.log('Road recognition: centers, ring/branch, separate borders, obstacles, narrow/empty, immutability, undo, roundtrip and stale detection passed.');

ring.map.entry={point:[0,4],edge:'left'};ring.map.junction=[0,4];ring.map.roadNetwork=network;
const ringBefore=copy(ring), route=routeFromRoads(ring);
assert.deepEqual(ring,ringBefore);
assert.deepEqual(route.points[0],[0,5]);assert.deepEqual(route.points.at(-1),route.points[0]);
assert.equal(route.points.length,network.edges.length*2+1);
const edgeKey=(a,b)=>[a.join(','),b.join(',')].sort().join(':');
assert.deepEqual(new Set(route.points.slice(1).map((p,i)=>edgeKey(route.points[i],p))),new Set(network.edges.map(([a,b])=>edgeKey(network.nodes[a],network.nodes[b]))));
assert.deepEqual(worldPoints(route),route.points.map(([x,y])=>[26*x,26*y]));
assert.equal(storeRoadRoute(ring),0);assert.equal(storeRoadRoute(ring),0);assert.equal(ring.map.paths.length,1);
syncJunction(ring);assert.deepEqual(ring.map.junction,[0,4]);
const movedEntry=copy(ring);movedEntry.map.entry={point:[7,11],edge:'bottom'};assert.ok(!roadRouteCurrent(movedEntry,route));
assert.ok(roadRouteCurrent(ring,route));ring.map.layers[0][0]='road';assert.ok(!roadRouteCurrent(ring,route));assert.throws(()=>routeFromRoads(ring),/识别/);
strips.map.entry={point:[3,0],edge:'top'};strips.map.roadNetwork=recognizeRoads(strips,catalog);assert.throws(()=>routeFromRoads(strips),/不连通/);
const dense=blank();put(dense,0,0,16,12);dense.map.entry={point:[7,11],edge:'bottom'};dense.map.roadNetwork=recognizeRoads(dense,catalog);
const longRoute=routeFromRoads(dense);assert.ok(longRoute.points.length>48 && longRoute.points.length<=1025);
dense.map.paths=Array.from({length:3},()=>({points:[[7,11]]}));assert.throws(()=>storeRoadRoute(dense),/三条/);assert.equal(dense.map.paths.length,3);
const undo=new History(ringBefore);undo.change(p=>storeRoadRoute(p));undo.undo();assert.deepEqual(undo.project,ringBefore);undo.redo();assert.equal(undo.project.map.paths.length,1);
console.log('Road routes: full-edge traversal, return/start, no mutation, coordinates, update in place, stale/disconnected/capacity rejection and undo passed.');
