import assert from 'node:assert/strict';
import fs from 'node:fs';
import {recognizeRoads,storeRoadRoute} from './road-network.js';
const {p,catalog}=JSON.parse(fs.readFileSync(0,'utf8'));
const fixed=recognizeRoads(p,catalog);
assert.deepEqual(fixed.uncovered,[]);
assert.equal(fixed.components,1);
p.map.roadNetwork=fixed;
storeRoadRoute(p);
const blocked=structuredClone(p);
blocked.prefabs.find(v=>v.id==='lamp').footprint.push([1,2]);
assert.ok(recognizeRoads(blocked,catalog).uncovered.some(([x,y])=>x===7&&y===5));
const loose=structuredClone(p);
loose.map.objects=[];
loose.map.layers[1][5*16+7]='outside:1425';
assert.deepEqual(recognizeRoads(loose,catalog).uncovered,[]);
loose.map.layers[1][5*16+7]='outside:1424';
assert.ok(recognizeRoads(loose,catalog).uncovered.some(([x,y])=>x===7&&y===5));
console.log('Roads traverse lamp shadows while lamp poles remain blocked, for complete objects and loose tiles.');
