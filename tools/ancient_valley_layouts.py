"""Approved ancient valley recipes and original animated shoreline assembly.

The checked-in JSON is the editable source. Regenerate the firmware table with
this module; previews and the resource pack use the very same original quarters.
"""
import copy
import json
from pathlib import Path

DATA_PATH = Path(__file__).with_suffix('.json')
DATA = json.loads(DATA_PATH.read_text())
TILE_SOURCES = {int(k): tuple(v) for k, v in DATA['tile_sources'].items()}
WATER_TILES = {int(k): v for k, v in DATA['water_tiles'].items()}
WATER_FIRST = min(WATER_TILES)
WATER_LAST = max(WATER_TILES)
CAVE_FLOOR = next(t for t, s in TILE_SOURCES.items() if s == ('Caves.png', 610))


def layout(edge):
    return copy.deepcopy(DATA['layouts'][int(edge)])


def water_frame(tile_id, sources, frame_index=0):
    from PIL import Image
    from generate_explore_map import autotile_variant

    spec = WATER_TILES[tile_id]
    source = sources[spec['source']]
    if 'variant' in spec:
        return autotile_variant(source, spec['variant'], frame_index)
    tile = Image.new('RGBA', (32, 32))
    for k, (quarter, flip_y) in enumerate(spec['quarters']):
        sx = (frame_index % 8) * 96 + quarter % 6 * 16
        sy = quarter // 6 * 16
        part = source.crop((sx, sy, sx + 16, sy + 16))
        if flip_y:
            part = part.transpose(Image.Transpose.FLIP_TOP_BOTTOM)
        tile.alpha_composite(part, (k % 2 * 16, k // 2 * 16))
    return tile


def cpp_table():
    def point(p):
        return '{' + ', '.join(map(str, p)) + '}'

    def endpoint(p, edge):
        return '{' + point(p) + ', static_cast<ExploreMapGenerator::Edge>(' + str(edge) + ')}'

    text = ['// Generated by tools/ancient_valley_layouts.py; edit its JSON source.',
            '#pragma once', '#include "game/ExploreMapGenerator.h"',
            'namespace ExploreAncientValley {',
            'using ExploreMapGenerator::Point;', 'using ExploreMapGenerator::Endpoint;',
            'struct Route { uint8_t count; Point controls[12]; Endpoint exit; };',
            'struct Layout { Endpoint entry; Point junction; Route routes[2];',
            '    uint16_t layers[3][192]; uint16_t water[12];',
            '    uint16_t solid[12]; uint16_t stairs[12]; };',
            f'constexpr uint16_t CAVE_FLOOR = {CAVE_FLOOR};',
            f'constexpr uint16_t WATER_FIRST = {WATER_FIRST};',
            f'constexpr uint16_t WATER_LAST = {WATER_LAST};',
            'constexpr bool waterTile(uint16_t t) { return t >= WATER_FIRST && t <= WATER_LAST; }',
            'constexpr bool openWater(uint16_t t) { return ' + ' || '.join(
                't == ' + str(t) for t, s in WATER_TILES.items()
                if 'variant' in s or s.get('quarters') == [[26, False], [27, False], [32, False], [33, False]]) + '; }',
            'constexpr uint16_t CAVE_SOURCES[] = {' + ', '.join(str(src[1]) for t, src in TILE_SOURCES.items() if src[0] == 'Caves.png') + '};',
            'constexpr uint16_t caveSource(uint16_t t) { return t >= 4800 && t < 4800 + sizeof(CAVE_SOURCES) / sizeof(CAVE_SOURCES[0]) ? CAVE_SOURCES[t - 4800] : 0; }',
            'constexpr bool caveGround(uint16_t t) { return caveSource(t) == 610 || (caveSource(t) >= 657 && caveSource(t) <= 675); }',
            'constexpr bool caveRock(uint16_t t) { return caveSource(t) >= 557 && caveSource(t) <= 559; }',
            'constexpr int depthRows(uint16_t t) { return caveSource(t) == 524 ? 2 : ((caveSource(t) >= 504 && caveSource(t) <= 532) || caveRock(t) ? 1 : 0); }',
            'constexpr Layout LAYOUTS[4] = {']
    for spec in DATA['layouts']:
        text += ['    { // ' + spec['key'].upper(),
                 '      ' + endpoint(spec['entry']['point'], spec['entry']['edge']) + ', ' + point(spec['junction']) + ', {']
        for route in spec['routes']:
            points = route['points']
            controls = [points[0]] + [p for a, p, b in zip(points, points[1:], points[2:])
                        if (p[0]-a[0], p[1]-a[1]) != (b[0]-p[0], b[1]-p[1])] + [points[-1]]
            assert len(controls) <= 12
            text += ['        {' + str(len(controls)) + ', {' + ', '.join(map(point, controls)) + '}, ' + endpoint(points[-1], route['edge']) + '},']
        text += ['      }, {']
        for layer in spec['layers']:
            text += ['        {'] + ['          ' + ', '.join(map(str, layer[y*16:y*16+16])) + ',' for y in range(12)] + ['        },']
        ports = {tuple(p['visual_anchor']) for p in spec['portals']}
        solid = (set(map(tuple, spec['walls'])) - ports) | set(map(tuple, spec['cliffs'])) | set(map(tuple, spec['decoration']))
        masks = [set(map(tuple, spec['water'])), solid, set(map(tuple, spec['stairs']))]
        text += ['      },']
        for cells in masks:
            text += ['      {' + ', '.join(str(sum(1 << x for x in range(16) if (x, y) in cells)) for y in range(12)) + '},']
        text += ['    },']
    text += ['};', '}  // namespace ExploreAncientValley', '']
    return __import__('content_tables').adapt_header('\n'.join(text),'ExploreAncientValleyLayouts')


if __name__ == '__main__':
    target = Path(__file__).resolve().parents[1] / 'src/game/ExploreAncientValleyLayouts.h'
    target.write_text(cpp_table())
    print(target)
