#!/usr/bin/env python3
"""Pack the checked-in Emerald evolution references (offline; requires Pillow)."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'origin_asset/evolution/emerald'
TARGET = ROOT / 'firmware/amoled_1_8_v1/main/ui/EvolutionBackgroundData.h'


def generate():
    provenance = json.loads((SOURCE / 'source.json').read_text())
    for name, expected in provenance['sha256'].items():
        assert hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() == expected, name
    image = Image.open(SOURCE / 'bg.png').convert('L')
    assert image.size == (128, 112)
    indexes = list(image.tobytes())
    assert all(i % 17 == 0 for i in indexes)
    atlas = [indexes[i] // 17 | (indexes[i+1] // 17 << 4) for i in range(0, len(indexes), 2)]
    palette = [tuple(map(int, s.split())) for s in (SOURCE / 'bg_anim.pal').read_text().splitlines()[3:]]
    sequences = json.loads((SOURCE / 'palette-index.json').read_text())
    assert len(palette) == 32 and len(sequences) == 50 and all(len(s) == 16 for s in sequences)
    colors = []
    for row in sequences:
        for i in row:
            r, g, b = palette[i]
            colors.append(((r & 248) << 8) | ((g & 252) << 3) | (b >> 3))
    out = ['// Generated by tools/generate_evolution_background.py. Do not edit.',
           '// Original assets: pret/pokeemerald; provenance in origin_asset/evolution/emerald/source.json.',
           '#pragma once', '#include <cstdint>', 'namespace AmoledV1::EvolutionBackgroundData {']
    def array(name, kind, values, digits):
        out.append(f'inline constexpr {kind} {name}[] = {{')
        for start in range(0, len(values), 16):
            out.append('    ' + ','.join(f'0x{v:0{digits}x}' for v in values[start:start+16]) + ',')
        out.append('};')
    array('tiles', 'uint8_t', atlas, 2)
    for name in ('inner', 'outer'):
        data = (SOURCE / f'bg_{name}.bin').read_bytes()
        assert len(data) == 2048
        values = struct.unpack('<1024H', data)
        assert all((v & 1023) < 224 for v in values)
        array(name, 'uint16_t', values, 4)
    array('palettes', 'uint16_t', colors, 4)
    def smooth(a, b, x):
        t = min(1, max(0, (x-a)/(b-a)))
        return t*t*(3-2*t)
    envelope = [int(255*.68*smooth(64,114,y)*(1-smooth(246,292,y))+.5) for y in range(448)]
    strengths = list(dict.fromkeys(envelope))
    array('strengths', 'uint8_t', strengths, 2)
    array('rowStrength', 'uint8_t', [strengths.index(v) for v in envelope], 2)
    out.append('} // namespace AmoledV1::EvolutionBackgroundData')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if TARGET.read_text() != content:
            raise SystemExit('Evolution background header is stale')
    else:
        TARGET.write_text(content)
    print('Evolution backdrop: packed tiles/maps/palettes 12864 bytes + 525-byte envelope; deterministic source check OK')


if __name__ == '__main__':
    main()
