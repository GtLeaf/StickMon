"""Compile approved grass recipes for bounded-cost generation on the device.

Three styles, two woodland modes, four entrances and four samples make 96 rooms.
The recipe remains procedural offline; runtime selection uses the expedition seed.
"""
from copy import deepcopy
from functools import lru_cache
from pathlib import Path

import generate_runtime_tile_map as g
from grass_path_layouts import generate, wants_fence, FENCED_CHANCE

ROOT = Path(__file__).resolve().parents[1]
SAMPLES = 4
# Keep the approved fenced examples in the pool, including their original seed.
APPROVED = {0: (4152714228,), 1: (1817700350, 1311826184), 2: (4087963263,)}
APPROVED_OPEN = {0: (1817700350, 3355331658), 1: (4152714228, 4083403139),
                 2: (1311826184, 4201854206)}


@lru_cache(None)
def recipe_seeds(style, fenced):
    seeds = list((APPROVED if fenced else APPROVED_OPEN)[style])
    i = 0
    while len(seeds) < SAMPLES:
        seed = g.derive_seed(0x20261031 + i, 0, style)
        i += 1
        if wants_fence(seed) == bool(fenced) and seed not in seeds:
            seeds.append(seed)
    return tuple(seeds)


@lru_cache(None)
def room(style, fenced, edge, sample):
    return generate(recipe_seeds(style, fenced)[sample], g.Edge(edge), style, bool(fenced))


def selection(seed):
    rng = g.XorShift32(seed ^ 0x6A09E667)
    return rng.bounded(3), int(wants_fence(seed)), rng.bounded(SAMPLES)


def generate_map(seed, edge):
    if not 0 <= int(edge) < 4:
        raise ValueError('invalid grass entrance')
    style, fenced, sample = selection(seed)
    result = deepcopy(room(style, fenced, int(edge), sample)[0])
    result.seed = seed
    return result


def all_rooms():
    return [room(style, fenced, edge, sample)
            for style in range(3) for fenced in range(2)
            for edge in range(4) for sample in range(SAMPLES)]


def cpp_table():
    rooms = all_rooms()
    tiles = sorted({tile for m, _ in rooms for layer in m.layers for tile in layer})
    assert len(tiles) <= 256
    ids = {tile: i for i, tile in enumerate(tiles)}
    lines = ['// Generated by tools/grass_path.py; edit grass_path_layouts.py.',
             '#pragma once', '#include <cstdint>', 'namespace ExploreGrassPathData {',
             'struct Point { uint8_t x,y; };',
             'struct Route { Point exit; uint8_t edge,count; Point points[48]; };',
             'struct Room { uint8_t layers[3][192]; Point entry,junction; Route paths[2]; };',
             f'constexpr uint8_t FENCED_CHANCE = {FENCED_CHANCE};',
             f'constexpr uint8_t SAMPLES = {SAMPLES};',
             'constexpr uint16_t TILES[] = {' + ','.join(map(str, tiles)) + '};',
             f'constexpr Room ROOMS[{len(rooms)}] = {{']
    point = lambda p: '{' + ','.join(map(str, p)) + '}'
    for m, meta in rooms:
        assert len(m.paths) == 2
        lines.append('  {{')
        lines += ['    {' + ','.join(str(ids[t]) for t in layer) + '},' for layer in m.layers]
        lines.append('  },' + point(m.entry.point) + ',' + point(m.junction) + ',{')
        for p in m.paths:
            assert len(p.points) <= 48
            lines.append('    {' + point(p.exit.point) + f',{int(p.exit.edge)},{len(p.points)},' +
                         '{' + ','.join(map(point, p.points)) + '}},')
        lines.append('  }},')
    lines += ['};', '} // namespace ExploreGrassPathData', '']
    return __import__('content_tables').adapt_header('\n'.join(lines), 'ExploreGrassPathData')


if __name__ == '__main__':
    text = cpp_table()
    path = ROOT / 'src/game/ExploreGrassPathData.h'
    path.write_text(text)
    print(f'{path}: {len(all_rooms())} approved grass recipes')
