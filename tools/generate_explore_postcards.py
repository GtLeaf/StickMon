"""Generate small indexed scene thumbnails for the reversible AMOLED postcard trial."""
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCES=[
'origin_asset/generated/game/explore_grass_path_01_416.png',
'origin_asset/generated/game/explore_creek_bridge_slope_01_416.png',
'origin_asset/generated/game/explore_natural_park_416.png',
'origin_asset/generated/game/runtime_frost_crystal_cave_v8/runtime_tile_map_01_aed452fc.png',
'origin_asset/mainScreen/menu/explore/bg_explore.png',
'origin_asset/generated/game/explore_ancient_waterfall_valley_01_416.png',
'origin_asset/explore_postcards/market.png']
def generate():
    lines=['// Generated by tools/generate_explore_postcards.py; 168x146, 64-colour row RLE.', '#pragma once', '#include <cstdint>', 'namespace ExplorePostcardArt {']
    for n,source in enumerate(SOURCES):
        im=Image.open(ROOT/source).convert('RGB');w,h=im.size;desired=w*292/336
        if h>desired:im=im.crop((0,int((h-desired)/2),w,int((h+desired)/2)))
        else:
            cw=h*336/292;im=im.crop((int((w-cw)/2),0,int((w+cw)/2),h))
        im=im.resize((168,146),Image.Resampling.NEAREST).quantize(colors=64,dither=Image.Dither.NONE)
        pal=im.getpalette();pal+= [0]*(192-len(pal));colors=[((pal[i*3]>>3)<<11)|((pal[i*3+1]>>2)<<5)|(pal[i*3+2]>>3) for i in range(64)]
        pixels=list(im.get_flattened_data());data=[];offsets=[0]
        for y in range(146):
            x=0
            while x<168:
                value=pixels[y*168+x];end=x+1
                while end<168 and pixels[y*168+end]==value:end+=1
                data.extend([end-x,value]);x=end
            offsets.append(len(data))
        for typ,name,values in [('uint16_t','palette',colors),('uint16_t','rows',offsets),('uint8_t','runs',data)]:
            lines.append(f'inline constexpr {typ} {name}{n}[] = {{')
            lines.extend(','.join(map(str,values[i:i+32]))+',' for i in range(0,len(values),32));lines.append('};')
    lines.append('struct Scene {const uint16_t* palette;const uint16_t* rows;const uint8_t* runs;};')
    lines.append('inline constexpr Scene scenes[] = {'+','.join('{palette%d,rows%d,runs%d}'%(i,i,i) for i in range(7))+'};\n}')
    (ROOT/'firmware/amoled_1_8_v1/main/ui/ExplorePostcardArt.h').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':generate()
