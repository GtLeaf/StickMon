TOO_LONG_PAYLOAD = "y" * 110


@unittest.skipUnless(shutil.which("c++"), "host C++ compiler is unavailable")
class QrCodeGenTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.binary = Path(tempfile.mkdtemp()) / "qr_code_gen_host"
        subprocess.run(
            [
                "c++",
                "-std=c++17",
                f"-I{ROOT / 'src'}",
                str(ROOT / "tools" / "qr_code_gen_host.cpp"),
                str(ROOT / "src" / "presentation" / "QrCodeGen.cpp"),
                "-o",
                str(cls.binary),
            ],
            check=True,
            capture_output=True,
            text=True,
        )

    def encode(self, payload):
        result = subprocess.run(
            [str(self.binary), payload],
            check=False,
            capture_output=True,
            text=True,
        )
        lines = result.stdout.splitlines()
        return int(lines[0]), lines[1:]

    def test_golden_matrices(self):
        for name, (payload, expected_rows) in GOLDENS.items():
            with self.subTest(case=name):
                size, rows = self.encode(payload)
                self.assertEqual(size, len(expected_rows))
                self.assertEqual(rows, expected_rows)

    def test_rejects_overlong_payload(self):
        size, _rows = self.encode(TOO_LONG_PAYLOAD)
        self.assertEqual(size, 0)


if __name__ == "__main__":
    unittest.main()
